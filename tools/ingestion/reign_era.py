# 中文数字字符 -> 值（元/正 = 元年/正月 = 1）
_CN = {
    "零": 0, "一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6,
    "七": 7, "八": 8, "九": 9, "十": 10, "廿": 20, "卅": 30,
    "元": 1, "正": 1,
}

# 十位字符 -> 基数
_TENS = {"十": 10, "廿": 20, "卅": 30}


def _cn_num(s):
    """中文数字(<=99) -> int。支持 元/一..九、十、十一..十九、
    二十..二十九、三十..三十九、四十..、以及 廿X / 卅X 变体。
    无法解析返回 None。"""
    if s is None:
        return None
    s = s.strip()
    if s in ("元", "正"):
        return 1
    if s in _CN:
        return _CN[s]
    tens_char = None
    for ch in ("十", "廿", "卅"):
        if ch in s:
            tens_char = ch
            break
    if tens_char is None:
        return None
    before, after = s.split(tens_char, 1)
    tens_mult = 1 if before == "" else _CN.get(before)
    if tens_mult is None:
        return None
    ones = _CN.get(after, 0) if after else 0
    return _TENS[tens_char] * tens_mult + ones


def to_gregorian(era, year):
    """年号 + 第N年 -> 公元年。year 可为 int 或中文数字字符串。"""
    if era not in ERAS:
        raise KeyError("未知年号: %s" % era)
    start, end, _dyn = ERAS[era]
    if isinstance(year, str):
        year = _cn_num(year)
    if not isinstance(year, int) or year < 1:
        raise ValueError("非法年份: %r" % (year,))
    g = start + (year - 1)
    if g > end:
        raise ValueError("%s 仅 %d 年（%d-%d），第 %d 年越界"
                         % (era, end - start + 1, start, end, year))
    return g


def normalize_year(s):
    """把年份字符串归一化为公元 int；无法识别返回 None。

    支持：
      - 纯数字        '1619'            -> 1619
      - 年号纪年      '万历四十七年'     -> 1619
      - 含「元/正」年号 '开元元年'        -> 713  （正则直接匹配已知年号名，不排斥元/正）
      - 带月份        '天命四年二月廿九' -> 1619  (取年号对应公元年，月日忽略)
      - 带干支括号    '天命四年（己未）' -> 1619
      - 复合表述首段  '万历四十七年即天命四年' -> 1619  (取最左年号)
    """
    if s is None:
        return None
    s = s.strip().replace("（", "(").replace("）", ")")
    s = re.sub(r"\(.*?\)", "", s).strip()
    s = s.translate(_TRAD2SIMP)  # 繁体年号 -> 简化，避免 ERAS 查表 miss
    # 公元前 / 前 纪年（如 公元前506年 / 前506年）
    m_bc = re.match(r"(?:公元|西元)?前\s*(\d{1,4})", s)
    if m_bc:
        return -int(m_bc.group(1))
    # 公元XXX年（如 公元208年）-> 208
    s = re.sub(r"^(?:公元|西元)", "", s).strip()
    if re.fullmatch(r"\d{1,4}年?", s):
        return int(re.sub(r"年", "", s))
    if re.fullmatch(r"\d{1,4}", s):
        return int(s)
    m = _ERA_RE.search(s)
    if not m:
        # 兜底：年号级模糊表述「年号+间/年间」（如 天启年间），史料未精确到第几年。
        # 取该年号起始公元年作为默认落点（保守置于纪年开端），供时间轴排序。
        mp = _ERA_PERIOD_RE.search(s)
        if mp and mp.group(1) in ERAS:
            return ERAS[mp.group(1)][0]
        return None
    era = m.group(1)
    ystr = m.group(2)
    y = _cn_num(ystr)
    if y is None:
        return None
    try:
        return to_gregorian(era, y)
    except (ValueError, KeyError):
        return None


def era_at(gregorian):
    """公元年 -> [(年号, 第N年, 朝代), ...]。重叠年份(如1644)会返回多条。"""
    out = []
    for era, (start, end, dyn) in ERAS.items():
        if start <= gregorian <= end:
            out.append((era, gregorian - start + 1, dyn))
    return out


