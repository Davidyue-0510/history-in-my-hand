def load_eras(path):
    """从 JSON 载入权威《中国历代纪年表》，覆盖/补全 ERAS（单一真值原则）。
    schema: {"eras":[[年号, 起, 止, 朝代], ...], "dynasties":[[朝代, 起, 止], ...]}
    返回载入的 (n_eras, n_dyn) 计数。"""
    import json
    with open(path, encoding="utf-8") as f:
        blob = json.load(f)
    n_e, n_d = 0, 0
    for row in blob.get("eras", []):
        era, s, e, dyn = row[0], int(row[1]), int(row[2]), row[3]
        ERAS[era] = (s, e, dyn)
        n_e += 1
    for row in blob.get("dynasties", []):
        name, s, e = row[0], int(row[1]), int(row[2])
        # 去重：同名下若有旧区间则替换（保留更细的权威区间）
        DYNASTIES[:] = [r for r in DYNASTIES if r[0] != name]
        DYNASTIES.append((name, s, e))
        n_d += 1
    return n_e, n_d


